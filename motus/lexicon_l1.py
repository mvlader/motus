#: Отрицатели: переворачивают знак ближайшего значимого хита. Сравниваются как
#: ЦЕЛЫЕ токены — иначе "не" ловится внутри "наконец", "меня", "неважно".
_NEGATORS = frozenset(("не", "нет", "ни", "без", "никак", "отнюдь", "нельзя"))

#: Усилители рядом с хитом множат его вклад (тоже целыми токенами).
_INTENS = frozenset(("очень", "супер", "крайне", "жутко", "дико", "чертовски",
                     "невероятно", "просто", "реально", "конкретно", "капитально",
                     "адски", "ужасно", "офигенно", "капец"))

_TOKEN_RE = re.compile(r"[а-яa-z0-9]+(?:-[а-яa-z0-9]+)?")


def _normalize(text: str) -> str:
    return text.lower().replace("ё", "е").strip()


def _tokens(norm: str) -> List[str]:
    return _TOKEN_RE.findall(norm)


def _hits(norm: str, toks: List[str], lexicon: Dict[str, float]) -> List[Tuple[float, int, bool]]:
    """Список (вес, индекс токена, has_neg). has_neg=True, если сама основа уже
    содержит отрицатель («не работает», «опять не») — тогда внешнюю проверку
    отрицания к ней применять нельзя, иначе двойной переворот знака.

    Однословная основа — префикс токена (>=4 симв. — ловит словоформы, короче —
    точное совпадение); фраза с пробелом — подстрока norm по границам слов."""
    out: List[Tuple[float, int, bool]] = []
    for stem, weight in lexicon.items():
        key = stem.replace("ё", "е").strip()
        has_neg = any(w in _NEGATORS for w in key.split())
        if " " in key:
            for m in re.finditer(r"(?<![а-яa-z])" + re.escape(key), norm):
                tok_i = len(_TOKEN_RE.findall(norm[: m.start()]))
                out.append((weight, tok_i, has_neg))
        else:
            for i, t in enumerate(toks):
                if t == key or (len(key) >= 4 and t.startswith(key)):
                    out.append((weight, i, has_neg))
    return out


def _near(toks: List[str], idx: int, words: frozenset, back: int = 4, fwd: int = 2) -> bool:
    lo, hi = max(0, idx - back), min(len(toks), idx + fwd + 1)
    return any(toks[j] in words for j in range(lo, hi))


def _caps_bang(text: str) -> Tuple[float, int]:
    letters = [c for c in text if c.isalpha()]
    caps_ratio = sum(1 for c in letters if c.isupper()) / max(1, len(letters))
    return caps_ratio, text.count("!")


def _score_signed(text: str, toks: List[str], norm: str, lexicon: Dict[str, float]) -> float:
    """Знаковая ось (valence, social_warmth): сумма с учётом отрицания и усиления."""
    caps_ratio, bang = _caps_bang(text)
    total = 0.0
    for weight, idx, has_neg in _hits(norm, toks, lexicon):
        w = weight
        # Отрицание в русском почти всегда ПЕРЕД словом: «не круто». «спасибо, что
        # не бросил» — «не» относится к «бросил», не к «спасибо», поэтому fwd=0.
        if not has_neg and _near(toks, idx, _NEGATORS, back=3, fwd=0):
            w = -w * 0.9
        if _near(toks, idx, _INTENS):
            w *= 1.5
        total += w
    if caps_ratio > 0.6 and len(text) > 8:
        total *= 1.4
    if bang >= 2:
        total *= 1.15 if total > 0 else 1.25
    return total


def _score_unsigned(text: str, toks: List[str], norm: str, lexicon: Dict[str, float]) -> float:
    _, bang = _caps_bang(text)
    total = 0.0
    for weight, idx, has_neg in _hits(norm, toks, lexicon):
        w = weight
        # Только непосредственно предшествующий отрицатель («не срочно») —
        # окно шире ловит «не» из «не могу, удаляю проект» и душит не тот хит.
        if not has_neg and idx > 0 and toks[idx - 1] in _NEGATORS:
            w *= 0.2
        if _near(toks, idx, _INTENS):
            w *= 1.3
        total += w
    if bang >= 2 and total > 0:
        total *= 1.1
    return total


#: (порог на ±1, порог на ±2). strict поднимает вход в ненулевое значение: слабый
#: одиночный хит («ярость от заката», «спасибо, удружил») больше не двигает ось.
_SIGNED_CUT = {False: (0.7, 2.2), True: (1.5, 2.6)}
_UNSIGNED_CUT = {False: (0.8, 2.0), True: (1.5, 2.4)}
_BLOCKED_CUT = {False: 1.0, True: 1.6}


def _bucket_signed(x: float, strict: bool) -> int:
    lo, hi = _SIGNED_CUT[strict]
    if x >= hi:
        return 2
    if x >= lo:
        return 1
    if x <= -hi:
        return -2
    if x <= -lo:
        return -1
    return 0


def _bucket_unsigned(x: float, strict: bool) -> int:
    lo, hi = _UNSIGNED_CUT[strict]
    if x >= hi:
        return 2
    if x >= lo:
        return 1
    return 0


def lexical_appraise(text: str, strict: bool = False) -> Appraisal:
    """Текст → Appraisal, детерминированно, без модели и без сети.

    strict=True — «полностью отсекать неправильный вывод»: пороги входа в ненулевое
    значение выше, косвенные связки отключены. Меньше ложных сильных сигналов ценой
    того, что часть настоящих слабых сенсор пропускает в ноль (безвредный промах).
    """
    if not text or not text.strip():
        return Appraisal()
    norm = _normalize(text)
    toks = _tokens(norm)

    valence = _bucket_signed(_score_signed(text, toks, norm, _VALENCE), strict)
    warmth = _bucket_signed(_score_signed(text, toks, norm, _WARMTH), strict)
    threat = _bucket_unsigned(_score_unsigned(text, toks, norm, _THREAT), strict)
    novelty = _bucket_unsigned(_score_unsigned(text, toks, norm, _NOVELTY), strict)
    loss = _bucket_unsigned(_score_unsigned(text, toks, norm, _LOSS), strict)
    blocked = _score_unsigned(text, toks, norm, _BLOCKED) >= _BLOCKED_CUT[strict]

    if not strict:
        # Косвенные связки: не прямые улики, а вывод. В strict отключены.
        # Оскорбление во втором лице — это и −valence, и −warmth разом.
        if warmth <= -1 and valence == 0:
            valence = -1
        # «удаляю проект и ухожу» — если loss=2, тон почти наверняка не нейтральный.
        if loss >= 2 and valence == 0:
            valence = -1

    return Appraisal(valence=valence, threat=threat, novelty=novelty,
                     social_warmth=warmth, loss=loss, agency_blocked=blocked)
