"""L-1, детерминированная ветка: текст сообщения → Appraisal без модели.

Зачем не модель. Шесть полей Appraisal грубые (−2..2 / 0..2 / bool), и пять из
шести — почти чисто лексические: благодарность, ругань, «срочно», «ухожу»,
«застрял» опознаются по словам, а не по смыслу. Бенчмарк (docs/04-model-l1.md)
это подтвердил: Qwen3-1.7B на этой задаче ловил ровно те же поверхностные маркеры,
что и словарь, платя за это ~10 с задержки, отдельным сервисом llama.cpp, 1 ГБ
памяти и нагревом Pi. Только `novelty` реально хочет семантику — и там модель тоже
промахивалась.

Что это даёт вместо модели: полная детерминированность (реплей воспроизводит
оценку из журнала без всякой сети — и теперь то же самое верно и на живом ходу),
ноль задержки, ноль зависимостей, ноль отдельных процессов. Ровно та изоляция
математики от модели, ради которой проект и затевался.

И главное — словарь **безопаснее** (прогон `--dataset all` с ловушками,
docs/04-model-l1.md): он никогда не выдумывает threat/loss/agency (для ненулевого
значения нужны конкретные слова), а модель — выдумывает («уезжаю в командировку» →
valence −2). Ошибки словаря — промах в ноль (безвредно, ядро не двигается) и
редкий переворот знака на чистом сарказме. `strict=True` режет и последнее вдвое.

Словарь ниже — не «наука», а рабочая гипотеза под конкретный кейс (один
разработчик, переписка с ботом, русский, контекст разработки). Правится свободно;
проверяется `tools/bench_l1_model.py --no-models --dataset all`.
"""

